//! IPv4 fragmentation of forwarded datagrams (MTU2 part B, NAT44-019L,
//! FWD-009, RFC 791 §3.2, RFC 1812 §§4.2.2.7, 5.2.7).
//!
//! A forwarded datagram without Don't Fragment that is longer than the MTU
//! of its egress interface MUST be fragmented (RFC 1812 §4.2.2.7). The
//! forwarding path decides it in the cold half of the egress MTU check,
//! after every forwarding, NAT, and firewall decision and their
//! prevalidation, and before anything commits:
//!
//! 1. [`Ipv4FragmentationRuntime::plan`] computes the fragment count from
//!    the RFC 791 algorithm and refuses, as a typed drop of the whole
//!    datagram, a count above `max-fragments-per-datagram`
//!    ([`crate::DropReason::Ipv4FragmentationTooManyFragments`]), a
//!    fragment whose offsets would not fit 13 bits (an overlong received
//!    fragment, [`crate::DropReason::Ipv4FragmentationOffsetOverflow`]), a
//!    datagram longer than a slot
//!    ([`crate::DropReason::Ipv4FragmentationDatagramTooLarge`]), or a full
//!    slot table ([`crate::DropReason::Ipv4FragmentationQueueFull`]).
//!    Nothing has committed then: no NAT mapping, session, or ID, no
//!    firewall state.
//! 2. The frame is rewritten as for any forwarded datagram (TTL, MACs, NAT
//!    translation, generated NAT ID), then [`Ipv4FragmentationRuntime::stage`]
//!    copies the datagram (Ethernet header plus Total Length bytes; any link
//!    padding is dropped) into a caller-owned slot. The NAT and firewall
//!    plans commit and the received frame is consumed as
//!    [`crate::ConsumeReason::Ipv4Fragmented`] (recycled by the backend).
//! 3. After the RX batch, [`execute_one_ipv4_fragmentation`] sends each
//!    staged datagram as fragments through the backend-owned generated-frame
//!    path of its egress. It first asks the session for room for the whole
//!    set ([`crate::GeneratedPacketBatch::check_capacity`]) and sends nothing
//!    when there is none, so the router never sends a partial set for lack
//!    of room. Then it allocates, writes, and commits the fragments in
//!    order.
//!
//! Fragment layout (RFC 791 §3.2, "An Example Fragmentation Procedure"):
//! with `NFB = (MTU - 20) / 8` fragment blocks per fragment, every fragment
//! but the last carries exactly `NFB * 8` data bytes (a multiple of 8), the
//! last carries the rest. Each fragment has the datagram's IPv4 header with
//! its own Total Length, the same Identification (already generated by the
//! NAT for a translated datagram, NAT44-126), the reserved flag as received,
//! DF clear, MF set on every fragment but the last, whose MF is the
//! datagram's own MF, and Fragment Offset = the datagram's offset plus the
//! fragment's data position / 8, so a fragment is re-fragmented correctly.
//! The header checksum is computed anew. The Ethernet header is the one the
//! forwarding decision wrote for the egress.
//!
//! Options: every forwarding path refuses an IPv4 header with options
//! before any decision (`IPV4_OPTIONS_UNSUPPORTED`, the NAT and the
//! firewall the same), so only 20-byte headers reach this module and no
//! option needs the RFC 791 copied-flag treatment. [`Ipv4FragmentationRuntime::plan`]
//! refuses anything else as [`crate::DropReason::Ipv4OptionsUnsupported`]
//! (fail closed). With a 20-byte header and the IPv4 minimum MTU of 68, a
//! datagram of 65535 bytes needs at most [`IPV4_FRAGMENTATION_MAX_FRAGMENTS`]
//! fragments.
//!
//! The slot table is filled during one RX batch and emptied by the
//! generated phase of the same tick; when that phase does not run (a
//! backend failure earlier in the tick), [`Ipv4FragmentationRuntime::flush`]
//! drops the staged datagrams and counts them. Staged datagrams therefore
//! never outlive their tick or their publication. No allocation: the slot
//! table and its bytes are caller-owned, sized once from the config.

use std::{marker::PhantomData, rc::Rc};

use crate::{
    ipv4_header_checksum, packet, DropReason, GeneratedAllocationError, GeneratedBatchCompletion,
    GeneratedPacketBatch, GeneratedPacketIo, IfId,
};

/// IPv4 header length of every fragmented datagram (no options).
const IPV4_HEADER_LEN: usize = 20;
/// Ethernet plus IPv4 header of a fragment.
const FRAGMENT_HEADERS_LEN: usize = packet::ETHERNET_HEADER_LEN + IPV4_HEADER_LEN;
const FLAG_RESERVED: u16 = 0x8000;
const FLAG_DONT_FRAGMENT: u16 = 0x4000;
const FLAG_MORE_FRAGMENTS: u16 = 0x2000;
const OFFSET_MASK: u16 = 0x1fff;

/// The most fragments any IPv4 datagram can need: 65535 bytes with a
/// 20-byte header at the IPv4 minimum MTU of 68 (48 data bytes per
/// fragment) is `ceil(65515 / 48)` = 1365. The upper bound of
/// `max-fragments-per-datagram`.
pub const IPV4_FRAGMENTATION_MAX_FRAGMENTS: u16 = 1365;

/// Default `max-fragments-per-datagram`: [`IPV4_FRAGMENTATION_MAX_FRAGMENTS`],
/// so by default every datagram RFC 1812 §4.2.2.7 requires the router to
/// fragment is fragmented (1500 → 1280 needs 2, 1500 → 576 3, 9000 → 1500
/// 7, 65535 → 68 1365). A lower value is hardening.
pub const IPV4_FRAGMENTATION_DEFAULT_MAX_FRAGMENTS: u16 = IPV4_FRAGMENTATION_MAX_FRAGMENTS;

/// Smallest `max-fragments-per-datagram`: one fragment is no fragmentation
/// (turn it off with `enabled = false` instead).
pub const IPV4_FRAGMENTATION_MIN_MAX_FRAGMENTS: u16 = 2;

/// Fragmentation switch and per-datagram bound.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Ipv4FragmentationPolicy {
    enabled: bool,
    max_fragments: u16,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[non_exhaustive]
pub enum Ipv4FragmentationPolicyError {
    /// `max-fragments-per-datagram` outside
    /// [`IPV4_FRAGMENTATION_MIN_MAX_FRAGMENTS`]..=[`IPV4_FRAGMENTATION_MAX_FRAGMENTS`].
    MaxFragmentsOutOfRange,
}

impl Ipv4FragmentationPolicy {
    /// RFC 1812 §4.2.2.7: fragmentation on, every datagram fragmented.
    pub const DEFAULT: Self = Self {
        enabled: true,
        max_fragments: IPV4_FRAGMENTATION_DEFAULT_MAX_FRAGMENTS,
    };

    /// `enabled = false` keeps the MTU1 behaviour: a DF-clear datagram above
    /// the egress MTU is `IPV4_FRAGMENTATION_REQUIRED` (hardening, against
    /// the RFC 1812 MUST).
    pub const fn new(
        enabled: bool,
        max_fragments: u16,
    ) -> Result<Self, Ipv4FragmentationPolicyError> {
        if max_fragments < IPV4_FRAGMENTATION_MIN_MAX_FRAGMENTS
            || max_fragments > IPV4_FRAGMENTATION_MAX_FRAGMENTS
        {
            return Err(Ipv4FragmentationPolicyError::MaxFragmentsOutOfRange);
        }
        Ok(Self {
            enabled,
            max_fragments,
        })
    }

    #[must_use]
    pub const fn enabled(self) -> bool {
        self.enabled
    }

    #[must_use]
    pub const fn max_fragments(self) -> u16 {
        self.max_fragments
    }
}

impl Default for Ipv4FragmentationPolicy {
    fn default() -> Self {
        Self::DEFAULT
    }
}

/// One staged datagram: its egress, the egress MTU, its frame length in the
/// slot bytes, and its fragment count.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Ipv4FragmentSlot {
    egress: IfId,
    mtu: u16,
    fragments: u16,
    frame_len: u32,
}

impl Ipv4FragmentSlot {
    pub const EMPTY: Self = Self {
        egress: IfId(0),
        mtu: 0,
        fragments: 0,
        frame_len: 0,
    };
}

/// Bytes of one slot for datagrams of at most `max_mtu` bytes: the
/// Ethernet header plus the datagram.
#[must_use]
pub const fn ipv4_fragment_slot_bytes(max_mtu: u16) -> usize {
    packet::ETHERNET_HEADER_LEN + max_mtu as usize
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[non_exhaustive]
pub enum Ipv4FragmentationStorageError {
    /// The byte storage is not `slots × slot_bytes` for a slot of at least
    /// one minimum-MTU datagram (14 + 68 bytes) and at most 14 + 65535.
    SlotBytes,
}

/// Cumulative fragmentation counters (never reset by a publication).
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub struct Ipv4FragmentationCounters {
    /// Datagrams staged for fragmentation by the RX phase.
    pub queued: usize,
    /// Staged datagrams whose every fragment was committed for TX.
    pub fragmented: usize,
    /// Fragments committed for TX.
    pub fragments: usize,
    /// Staged datagrams dropped whole because the egress session had no
    /// room for the whole fragment set (`check_capacity` returned
    /// `Unavailable`: pool, TX ring, unknown egress, or stopped backend).
    pub dropped_unavailable: usize,
    /// Staged datagrams dropped whole because the egress session refused
    /// the largest fragment's length (`FrameTooLarge`/`ZeroLength`).
    pub dropped_frame_too_large: usize,
    /// Staged datagrams whose set was cut short after `check_capacity`
    /// promised room: an allocation failed or a lease had the wrong length,
    /// both backend faults. The fragments committed before it were sent.
    pub incomplete: usize,
    /// Staged datagrams dropped because the generated phase did not run in
    /// their tick (an earlier backend failure).
    pub flushed: usize,
}

/// What happened to one staged datagram.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Ipv4FragmentOutcome {
    /// Every fragment was committed for TX.
    Sent,
    /// The session refused room for the set; nothing was allocated or sent.
    Refused(GeneratedAllocationError),
    /// An allocation failed after `check_capacity` promised room (a backend
    /// fault); `committed` fragments had been committed.
    AllocationFailed {
        committed: u16,
        error: GeneratedAllocationError,
    },
    /// A lease did not have the requested length (a backend contract
    /// violation); it was cancelled and the set stopped after `committed`.
    WrongLength { committed: u16 },
}

/// Report of one staged datagram's generated session.
#[derive(Debug, Eq, PartialEq)]
pub struct GeneratedIpv4FragmentReport<E> {
    pub egress: IfId,
    pub fragments: u16,
    pub outcome: Ipv4FragmentOutcome,
    pub completion: GeneratedBatchCompletion<E>,
}

/// The fragment count and staged frame length of an admitted datagram.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) struct Ipv4FragmentPlan {
    fragments: u16,
    frame_len: usize,
    mtu: u16,
}

impl Ipv4FragmentPlan {
    pub(crate) const fn fragments(self) -> u16 {
        self.fragments
    }
}

/// Caller-backed, worker-local fragmentation slot table.
///
/// ```compile_fail
/// fn require_send<T: Send>() {}
/// require_send::<ruster_core::Ipv4FragmentationRuntime<'static>>();
/// ```
pub struct Ipv4FragmentationRuntime<'a> {
    policy: Ipv4FragmentationPolicy,
    slots: &'a mut [Ipv4FragmentSlot],
    bytes: &'a mut [u8],
    slot_bytes: usize,
    /// Next staged slot to send.
    head: usize,
    /// Staged slots are `slots[head..len]`.
    len: usize,
    counters: Ipv4FragmentationCounters,
    _worker_local: PhantomData<Rc<()>>,
}

impl<'a> Ipv4FragmentationRuntime<'a> {
    /// Builds an empty runtime over `slots.len()` slots of
    /// `bytes.len() / slots.len()` bytes each (see
    /// [`ipv4_fragment_slot_bytes`]). With no slot, `bytes` must be empty
    /// and every datagram that needs fragmentation is
    /// [`DropReason::Ipv4FragmentationQueueFull`].
    pub fn new(
        policy: Ipv4FragmentationPolicy,
        slots: &'a mut [Ipv4FragmentSlot],
        bytes: &'a mut [u8],
    ) -> Result<Self, Ipv4FragmentationStorageError> {
        let slot_bytes = if slots.is_empty() {
            if !bytes.is_empty() {
                return Err(Ipv4FragmentationStorageError::SlotBytes);
            }
            0
        } else {
            let slot_bytes = bytes.len() / slots.len();
            if slot_bytes * slots.len() != bytes.len()
                || slot_bytes < ipv4_fragment_slot_bytes(crate::IPV4_MIN_MTU)
                || slot_bytes > ipv4_fragment_slot_bytes(u16::MAX)
            {
                return Err(Ipv4FragmentationStorageError::SlotBytes);
            }
            slot_bytes
        };
        slots.fill(Ipv4FragmentSlot::EMPTY);
        bytes.fill(0);
        Ok(Self {
            policy,
            slots,
            bytes,
            slot_bytes,
            head: 0,
            len: 0,
            counters: Ipv4FragmentationCounters::default(),
            _worker_local: PhantomData,
        })
    }

    #[must_use]
    pub const fn policy(&self) -> Ipv4FragmentationPolicy {
        self.policy
    }

    #[must_use]
    pub const fn counters(&self) -> Ipv4FragmentationCounters {
        self.counters
    }

    /// Staged datagrams not sent yet.
    #[must_use]
    pub const fn pending(&self) -> usize {
        self.len - self.head
    }

    #[must_use]
    pub const fn slot_capacity(&self) -> usize {
        self.slots.len()
    }

    #[must_use]
    pub const fn slot_bytes(&self) -> usize {
        self.slot_bytes
    }

    /// Drops every staged datagram (counted as `flushed`) and returns how
    /// many there were. The tick calls it when its generated fragment phase
    /// cannot run, so nothing staged outlives its tick.
    pub fn flush(&mut self) -> usize {
        let pending = self.pending();
        self.counters.flushed += pending;
        self.head = 0;
        self.len = 0;
        pending
    }

    /// Decides whether the DF-clear datagram in `frame` (validated IPv4,
    /// longer than `mtu`) can be fragmented for an egress of `mtu`, without
    /// changing anything. Cold path.
    pub(crate) fn plan(&self, frame: &[u8], mtu: u16) -> Result<Ipv4FragmentPlan, DropReason> {
        if !self.policy.enabled {
            return Err(DropReason::Ipv4FragmentationRequired);
        }
        let header = packet::ETHERNET_HEADER_LEN;
        let version_ihl = *frame.get(header).ok_or(DropReason::Ipv4HeaderTruncated)?;
        if usize::from(version_ihl & 0x0f) * 4 != IPV4_HEADER_LEN {
            return Err(DropReason::Ipv4OptionsUnsupported);
        }
        let total_len =
            packet::read_u16(frame, header + 2).ok_or(DropReason::Ipv4HeaderTruncated)?;
        let flags_offset =
            packet::read_u16(frame, header + 6).ok_or(DropReason::Ipv4HeaderTruncated)?;
        let data_len = usize::from(total_len)
            .checked_sub(IPV4_HEADER_LEN)
            .ok_or(DropReason::Ipv4TotalLengthTooSmall)?;
        let block = fragment_block(mtu);
        if data_len == 0 || block == 0 {
            // Not reachable for a datagram longer than an MTU of at least 68.
            return Err(DropReason::Ipv4FragmentationRequired);
        }
        let fragments = data_len.div_ceil(block);
        if fragments > usize::from(self.policy.max_fragments) {
            return Err(DropReason::Ipv4FragmentationTooManyFragments);
        }
        let last_offset = usize::from(flags_offset & OFFSET_MASK) + (fragments - 1) * block / 8;
        if last_offset > usize::from(OFFSET_MASK) {
            return Err(DropReason::Ipv4FragmentationOffsetOverflow);
        }
        let frame_len = header + usize::from(total_len);
        // With no slot at all the table is simply full (below).
        if frame_len > frame.len() || (!self.slots.is_empty() && frame_len > self.slot_bytes) {
            return Err(DropReason::Ipv4FragmentationDatagramTooLarge);
        }
        if self.len == self.slots.len() {
            return Err(DropReason::Ipv4FragmentationQueueFull);
        }
        Ok(Ipv4FragmentPlan {
            fragments: u16::try_from(fragments).expect("bounded by max_fragments"),
            frame_len,
            mtu,
        })
    }

    /// Copies the rewritten datagram of an admitted `plan` into the next
    /// slot. Infallible for a plan of this runtime made for this frame with
    /// no stage in between.
    pub(crate) fn stage(&mut self, frame: &[u8], plan: Ipv4FragmentPlan, egress: IfId) {
        let index = self.len;
        let start = index * self.slot_bytes;
        self.bytes[start..start + plan.frame_len].copy_from_slice(&frame[..plan.frame_len]);
        self.slots[index] = Ipv4FragmentSlot {
            egress,
            mtu: plan.mtu,
            fragments: plan.fragments,
            frame_len: u32::try_from(plan.frame_len).expect("bounded by the slot bytes"),
        };
        self.len += 1;
        self.counters.queued += 1;
    }

    fn take_front(&mut self) -> Option<(Ipv4FragmentSlot, usize)> {
        if self.head == self.len {
            self.head = 0;
            self.len = 0;
            return None;
        }
        let index = self.head;
        self.head += 1;
        if self.head == self.len {
            self.head = 0;
            self.len = 0;
        }
        Some((self.slots[index], index * self.slot_bytes))
    }
}

/// Data bytes of every fragment but the last for an egress of `mtu`: the
/// largest multiple of 8 that fits after a 20-byte header (RFC 791 §3.2).
#[must_use]
const fn fragment_block(mtu: u16) -> usize {
    let room = mtu as usize;
    if room <= IPV4_HEADER_LEN {
        return 0;
    }
    (room - IPV4_HEADER_LEN) / 8 * 8
}

/// Writes fragment `index` of the staged datagram `staged` (Ethernet header
/// plus the whole datagram) cut in blocks of `block` data bytes into `out`,
/// which must be exactly the fragment's frame length.
fn write_fragment(staged: &[u8], block: usize, index: usize, out: &mut [u8]) {
    let header = packet::ETHERNET_HEADER_LEN;
    let data = &staged[FRAGMENT_HEADERS_LEN..];
    let start = index * block;
    let len = block.min(data.len() - start);
    let last = start + len == data.len();
    let flags_offset = u16::from_be_bytes([staged[header + 6], staged[header + 7]]);
    let more = if last {
        flags_offset & FLAG_MORE_FRAGMENTS
    } else {
        FLAG_MORE_FRAGMENTS
    };
    let offset = (flags_offset & OFFSET_MASK) + u16::try_from(start / 8).expect("13-bit offset");
    let word = (flags_offset & FLAG_RESERVED) | more | offset;
    out[..FRAGMENT_HEADERS_LEN].copy_from_slice(&staged[..FRAGMENT_HEADERS_LEN]);
    let total_len = u16::try_from(IPV4_HEADER_LEN + len).expect("fragment within its MTU");
    out[header + 2..header + 4].copy_from_slice(&total_len.to_be_bytes());
    out[header + 6..header + 8].copy_from_slice(&word.to_be_bytes());
    out[header + 10..header + 12].copy_from_slice(&[0, 0]);
    let checksum = ipv4_header_checksum(&out[header..FRAGMENT_HEADERS_LEN]);
    out[header + 10..header + 12].copy_from_slice(&checksum.to_be_bytes());
    out[FRAGMENT_HEADERS_LEN..].copy_from_slice(&data[start..start + len]);
    debug_assert_eq!(
        flags_offset & FLAG_DONT_FRAGMENT,
        0,
        "only DF-clear is staged"
    );
}

/// Sends the oldest staged datagram as fragments through one generated
/// session on its egress, or returns `None` when nothing is staged.
///
/// The whole set is checked first ([`GeneratedPacketBatch::check_capacity`]
/// with the count and the first, longest fragment's frame length); a
/// refusal sends nothing and drops the datagram
/// ([`Ipv4FragmentOutcome::Refused`]). Then each fragment is allocated with
/// its exact frame length, written, and committed in order. The datagram
/// leaves its slot in every case.
pub fn execute_one_ipv4_fragmentation<I>(
    io: &mut I,
    runtime: &mut Ipv4FragmentationRuntime<'_>,
) -> Option<GeneratedIpv4FragmentReport<I::Error>>
where
    I: GeneratedPacketIo,
{
    let (slot, start) = runtime.take_front()?;
    let staged = &runtime.bytes[start..start + slot.frame_len as usize];
    let block = fragment_block(slot.mtu);
    let data_len = staged.len() - FRAGMENT_HEADERS_LEN;
    let largest = FRAGMENT_HEADERS_LEN + block.min(data_len);
    let mut batch = io.begin_generated(slot.egress);
    let outcome = match batch.check_capacity(usize::from(slot.fragments), largest) {
        Err(error) => Ipv4FragmentOutcome::Refused(error),
        Ok(()) => send_fragments(&mut batch, staged, block, slot.fragments),
    };
    let completion = batch.finish();
    let counters = &mut runtime.counters;
    match outcome {
        Ipv4FragmentOutcome::Sent => {
            counters.fragmented += 1;
            counters.fragments += usize::from(slot.fragments);
        }
        Ipv4FragmentOutcome::Refused(GeneratedAllocationError::Unavailable) => {
            counters.dropped_unavailable += 1;
        }
        Ipv4FragmentOutcome::Refused(_) => counters.dropped_frame_too_large += 1,
        Ipv4FragmentOutcome::AllocationFailed { committed, .. }
        | Ipv4FragmentOutcome::WrongLength { committed } => {
            counters.incomplete += 1;
            counters.fragments += usize::from(committed);
        }
    }
    Some(GeneratedIpv4FragmentReport {
        egress: slot.egress,
        fragments: slot.fragments,
        outcome,
        completion,
    })
}

fn send_fragments<B: GeneratedPacketBatch>(
    batch: &mut B,
    staged: &[u8],
    block: usize,
    fragments: u16,
) -> Ipv4FragmentOutcome {
    let data_len = staged.len() - FRAGMENT_HEADERS_LEN;
    for index in 0..fragments {
        let start = usize::from(index) * block;
        let frame_len = FRAGMENT_HEADERS_LEN + block.min(data_len - start);
        let mut lease = match batch.allocate(frame_len) {
            Ok(lease) => lease,
            Err(error) => {
                return Ipv4FragmentOutcome::AllocationFailed {
                    committed: index,
                    error,
                }
            }
        };
        let bytes = lease.bytes_mut();
        if bytes.len() != frame_len {
            lease.cancel();
            return Ipv4FragmentOutcome::WrongLength { committed: index };
        }
        write_fragment(staged, block, usize::from(index), bytes);
        lease.commit();
    }
    Ipv4FragmentOutcome::Sent
}

