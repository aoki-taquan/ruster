    /// Helper: compute IPv4 header checksum and write it into the header.
    fn set_ipv4_checksum(hdr: &mut [u8]) {
        hdr[10] = 0x00;
        hdr[11] = 0x00;
        let mut sum: u32 = 0;
        for i in (0..hdr.len()).step_by(2) {
            let word = if i + 1 < hdr.len() {
                u16::from_be_bytes([hdr[i], hdr[i + 1]])
            } else {
                u16::from_be_bytes([hdr[i], 0])
            };
            sum += word as u32;
        }
        while (sum >> 16) != 0 {
            sum = (sum & 0xFFFF) + (sum >> 16);
        }
        let cksum = !(sum as u16);
        hdr[10] = (cksum >> 8) as u8;
        hdr[11] = (cksum & 0xFF) as u8;
    }

    /// Build a valid Ethernet + IPv4 + UDP packet for testing.
    fn make_test_packet(
        src_mac: [u8; 6],
        dst_mac: [u8; 6],
        src_ip: [u8; 4],
        dst_ip: [u8; 4],
        ttl: u8,
        protocol: u8,
    ) -> Vec<u8> {
        let mut pkt = Vec::new();
        // Ethernet header (14 bytes)
        pkt.extend_from_slice(&dst_mac);
        pkt.extend_from_slice(&src_mac);
        pkt.extend_from_slice(&[0x08, 0x00]); // EtherType IPv4

        // IPv4 header (20 bytes)
        let ipv4_start = pkt.len();
        pkt.push(0x45); // version=4, IHL=5
        pkt.push(0x00); // DSCP/ECN
        let total_len: u16 = 20 + 8; // IP header + 8 bytes payload
        pkt.extend_from_slice(&total_len.to_be_bytes());
        pkt.extend_from_slice(&[0x00, 0x00]); // identification
        pkt.extend_from_slice(&[0x00, 0x00]); // flags/fragment
        pkt.push(ttl);
        pkt.push(protocol);
        pkt.extend_from_slice(&[0x00, 0x00]); // checksum placeholder
        pkt.extend_from_slice(&src_ip);
        pkt.extend_from_slice(&dst_ip);

        set_ipv4_checksum(&mut pkt[ipv4_start..ipv4_start + 20]);

        // Minimal payload (8 bytes — e.g., UDP header)
        pkt.extend_from_slice(&[0x00, 0x50]); // src port: 80
        pkt.extend_from_slice(&[0x00, 0x51]); // dst port: 81
        pkt.extend_from_slice(&[0x00, 0x08]); // length: 8
        pkt.extend_from_slice(&[0x00, 0x00]); // checksum: 0

        pkt
    }

    /// Verify the IPv4 header checksum in a packet slice is valid.
    fn verify_ipv4_checksum(ipv4_header: &[u8]) -> bool {
        let mut sum: u32 = 0;
        for i in (0..ipv4_header.len()).step_by(2) {
            let word = if i + 1 < ipv4_header.len() {
                u16::from_be_bytes([ipv4_header[i], ipv4_header[i + 1]])
            } else {
                u16::from_be_bytes([ipv4_header[i], 0])
            };
            sum += word as u32;
        }
        while (sum >> 16) != 0 {
            sum = (sum & 0xFFFF) + (sum >> 16);
        }
        sum as u16 == 0xFFFF
    }

    /// Verify the ICMP checksum in a message slice is valid.
    fn verify_icmp_checksum(icmp_msg: &[u8]) -> bool {
        let mut sum: u32 = 0;
        for i in (0..icmp_msg.len()).step_by(2) {
            let word = if i + 1 < icmp_msg.len() {
                u16::from_be_bytes([icmp_msg[i], icmp_msg[i + 1]])
            } else {
                u16::from_be_bytes([icmp_msg[i], 0])
            };
            sum += word as u32;
        }
        while (sum >> 16) != 0 {
            sum = (sum & 0xFFFF) + (sum >> 16);
        }
        sum as u16 == 0xFFFF
    }

    // ── TTL Exceeded tests ──────────────────────────────────────────

    #[test]
    fn ttl_exceeded_generates_icmp() {
        let src_mac = [0xAA, 0xBB, 0xCC, 0xDD, 0xEE, 0xFF];
        let dst_mac = [0x00, 0x11, 0x22, 0x33, 0x44, 0x55];
        let src_ip = [192, 168, 1, 100];
        let dst_ip = [8, 8, 8, 8];
        let router_ip = [192, 168, 1, 1];

        let original = make_test_packet(src_mac, dst_mac, src_ip, dst_ip, 1, 17);
        let reply = generate_icmp_error(&original, IcmpError::TtlExceeded, router_ip, "lan0")
            .expect("should generate ICMP reply");

        assert_eq!(reply.egress_iface, "lan0");

        let data = &reply.data;

        // Check Ethernet header: MACs are swapped.
        assert_eq!(&data[0..6], &src_mac); // dst = original src
        assert_eq!(&data[6..12], &dst_mac); // src = original dst
        assert_eq!(&data[12..14], &[0x08, 0x00]); // EtherType IPv4

        // Check IPv4 header.
        let ipv4 = &data[ETH_HEADER_LEN..ETH_HEADER_LEN + IPV4_HEADER_LEN];
        assert_eq!(ipv4[0], 0x45); // version=4, IHL=5
        assert_eq!(ipv4[8], ICMP_ERROR_TTL); // TTL = 64
        assert_eq!(ipv4[9], IP_PROTO_ICMP); // protocol = ICMP
        assert_eq!(&ipv4[12..16], &router_ip); // src = router IP
        assert_eq!(&ipv4[16..20], &src_ip); // dst = original src IP

        // Check ICMP header.
        let icmp_start = ETH_HEADER_LEN + IPV4_HEADER_LEN;
        assert_eq!(data[icmp_start], 11); // Type: Time Exceeded
        assert_eq!(data[icmp_start + 1], 0); // Code: 0

        // ICMP payload should contain original IP header + 8 bytes.
        let icmp_payload_start = icmp_start + ICMP_HEADER_LEN;
        let expected_payload = &original[ETH_HEADER_LEN..ETH_HEADER_LEN + 28];
        assert_eq!(
            &data[icmp_payload_start..icmp_payload_start + 28],
            expected_payload
        );
    }

    #[test]
    fn net_unreachable_generates_icmp() {
        let original =
            make_test_packet([0xAA; 6], [0xBB; 6], [10, 0, 0, 5], [172, 16, 0, 1], 64, 17);
        let router_ip = [10, 0, 0, 1];

        let reply = generate_icmp_error(&original, IcmpError::NetUnreachable, router_ip, "wan0")
            .expect("should generate ICMP reply");

        let icmp_start = ETH_HEADER_LEN + IPV4_HEADER_LEN;
        assert_eq!(reply.data[icmp_start], 3); // Type: Destination Unreachable
        assert_eq!(reply.data[icmp_start + 1], 0); // Code: Net Unreachable
        assert_eq!(reply.egress_iface, "wan0");
    }

    #[test]
