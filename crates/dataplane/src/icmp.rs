//! ICMP error message generation for the ruster dataplane.
//!
//! When the router drops a packet due to TTL expiration or unreachable
//! destination, it should generate an ICMP error message back to the
//! original sender per RFC 792.
//!
//! RFC-REF: RFC 792
//! "The Internet Protocol is not designed to be absolutely reliable.
//! The purpose of these control messages is to provide feedback about
//! problems in the communication environment [...]"
//!
//! # Loop prevention
//!
//! RFC-REF: RFC 792
//! "No ICMP error messages are sent about ICMP error messages."
//! We suppress ICMP error generation when the original packet is itself
//! an ICMP message (protocol = 1) to prevent infinite loops.

/// ICMP error types that can be generated by the router.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IcmpError {
    /// Time Exceeded: TTL expired in transit.
    ///
    /// RFC-REF: RFC 792 Section "Time Exceeded Message"
    /// Type = 11, Code = 0: time to live exceeded in transit.
    TtlExceeded,

    /// Destination Unreachable: network unreachable.
    ///
    /// RFC-REF: RFC 792 Section "Destination Unreachable Message"
    /// Type = 3, Code = 0: net unreachable.
    NetUnreachable,

    /// Destination Unreachable: host unreachable.
    ///
    /// RFC-REF: RFC 792 Section "Destination Unreachable Message"
    /// Type = 3, Code = 1: host unreachable.
    HostUnreachable,
}

impl IcmpError {
    /// Return the (type, code) pair for this ICMP error.
    fn type_code(&self) -> (u8, u8) {
        match self {
            IcmpError::TtlExceeded => (11, 0),
            IcmpError::NetUnreachable => (3, 0),
            IcmpError::HostUnreachable => (3, 1),
        }
    }
}

/// An ICMP reply packet ready for transmission.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IcmpReply {
    /// The interface on which to transmit this reply (back towards the sender).
    pub egress_iface: String,
    /// The complete Ethernet frame (Ethernet + IPv4 + ICMP) to transmit.
    pub data: Vec<u8>,
}

// ── Constants ───────────────────────────────────────────────────────

/// Minimum Ethernet header size.
const ETH_HEADER_LEN: usize = 14;

/// Standard IPv4 header size (no options).
const IPV4_HEADER_LEN: usize = 20;

/// ICMP header size: type(1) + code(1) + checksum(2) + unused(4) = 8.
const ICMP_HEADER_LEN: usize = 8;

/// EtherType for IPv4.
const ETHERTYPE_IPV4: u16 = 0x0800;

/// IPv4 protocol number for ICMP.
const IP_PROTO_ICMP: u8 = 1;

/// Minimum original packet length needed to generate an ICMP error:
/// Ethernet(14) + IPv4(20) + 8 bytes of original payload.
const MIN_ORIGINAL_PACKET_LEN: usize = ETH_HEADER_LEN + IPV4_HEADER_LEN + 8;

/// TTL for generated ICMP error packets.
const ICMP_ERROR_TTL: u8 = 64;

// ── Public API ──────────────────────────────────────────────────────

/// Generate an ICMP error message in response to a dropped packet.
///
/// The generated packet includes:
/// - Swapped Ethernet MACs (reply goes back towards the sender)
/// - New IPv4 header (src = `router_ip`, dst = original src IP, TTL = 64)
/// - ICMP header (type/code from `error`, checksum computed, 4 unused bytes)
/// - Original IP header + first 8 bytes of original payload
///
/// RFC-REF: RFC 792
/// "Every ICMP error message includes the Internet header and at least
/// the first 8 data octets of the datagram that triggered the error."
///
/// Returns `None` if:
/// - The original packet is too short (< 42 bytes: 14 Ethernet + 20 IPv4 + 8 payload)
/// - The original packet is not IPv4
/// - The original packet is itself ICMP (loop prevention per RFC 792)
pub fn generate_icmp_error(
    original_packet: &[u8],
    error: IcmpError,
    router_ip: [u8; 4],
    egress_iface: &str,
) -> Option<IcmpReply> {
    // ── Validate original packet ────────────────────────────────────
    if original_packet.len() < MIN_ORIGINAL_PACKET_LEN {
        return None;
    }

    // Check EtherType is IPv4.
    let ethertype = u16::from_be_bytes([original_packet[12], original_packet[13]]);
    if ethertype != ETHERTYPE_IPV4 {
        return None;
    }

    // Extract original IPv4 header fields.
    let orig_ipv4 = &original_packet[ETH_HEADER_LEN..];
    let orig_ihl = ((orig_ipv4[0] & 0x0F) as usize) * 4;
    if orig_ihl < IPV4_HEADER_LEN {
        return None;
    }
    let orig_protocol = orig_ipv4[9];

    // RFC-REF: RFC 792
    // "No ICMP error messages are sent about ICMP error messages."
    // Suppress ICMP generation for any ICMP packet to prevent loops.
    if orig_protocol == IP_PROTO_ICMP {
        return None;
    }

    // Extract original source IP (this becomes the ICMP reply destination).
    let orig_src_ip: [u8; 4] = [orig_ipv4[12], orig_ipv4[13], orig_ipv4[14], orig_ipv4[15]];

    // ── Build the ICMP payload ──────────────────────────────────────
    // RFC-REF: RFC 792
    // "Internet Header + 64 bits of Original Data Datagram"
    // We include the original IP header + first 8 bytes of the original
    // transport payload.
    let orig_ip_header_and_payload_len = orig_ihl + 8;
    let avail = original_packet.len() - ETH_HEADER_LEN;
    let icmp_payload_len = orig_ip_header_and_payload_len.min(avail);
    let icmp_payload = &orig_ipv4[..icmp_payload_len];

    // ── Build the reply packet ──────────────────────────────────────
    let icmp_total_len = ICMP_HEADER_LEN + icmp_payload_len;
    let ipv4_total_len = (IPV4_HEADER_LEN + icmp_total_len) as u16;
    let total_frame_len = ETH_HEADER_LEN + IPV4_HEADER_LEN + icmp_total_len;

    let mut pkt = Vec::with_capacity(total_frame_len);

    // ── Ethernet header (swapped MACs) ──────────────────────────────
    // dst MAC = original src MAC (reply back to sender)
    pkt.extend_from_slice(&original_packet[6..12]);
    // src MAC = original dst MAC (our interface MAC)
    pkt.extend_from_slice(&original_packet[0..6]);
    // EtherType: IPv4
    pkt.extend_from_slice(&ETHERTYPE_IPV4.to_be_bytes());

    // ── IPv4 header ─────────────────────────────────────────────────
    let ipv4_start = pkt.len();
    pkt.push(0x45); // version=4, IHL=5
    pkt.push(0x00); // DSCP/ECN
    pkt.extend_from_slice(&ipv4_total_len.to_be_bytes());
    pkt.extend_from_slice(&[0x00, 0x00]); // identification
    pkt.extend_from_slice(&[0x00, 0x00]); // flags/fragment
    pkt.push(ICMP_ERROR_TTL);
    pkt.push(IP_PROTO_ICMP);
    pkt.extend_from_slice(&[0x00, 0x00]); // checksum placeholder
    pkt.extend_from_slice(&router_ip);
    pkt.extend_from_slice(&orig_src_ip);

    // Compute IPv4 header checksum.
    compute_ipv4_checksum(&mut pkt[ipv4_start..ipv4_start + IPV4_HEADER_LEN]);

    // ── ICMP header ─────────────────────────────────────────────────
    let (icmp_type, icmp_code) = error.type_code();
    let icmp_start = pkt.len();
    pkt.push(icmp_type);
    pkt.push(icmp_code);
    pkt.extend_from_slice(&[0x00, 0x00]); // checksum placeholder
    pkt.extend_from_slice(&[0x00, 0x00, 0x00, 0x00]); // 4 unused bytes

    // ── ICMP payload (original IP header + 8 bytes) ─────────────────
    pkt.extend_from_slice(icmp_payload);

    // Compute ICMP checksum over header + payload.
    compute_icmp_checksum(&mut pkt[icmp_start..]);

    Some(IcmpReply {
        egress_iface: egress_iface.to_string(),
        data: pkt,
    })
}

// ── Checksum helpers ────────────────────────────────────────────────

/// Compute and write the IPv4 header checksum in place.
fn compute_ipv4_checksum(hdr: &mut [u8]) {
    // Zero checksum field first.
    hdr[10] = 0x00;
    hdr[11] = 0x00;
    let cksum = internet_checksum(hdr);
    hdr[10] = (cksum >> 8) as u8;
    hdr[11] = (cksum & 0xFF) as u8;
}

/// Compute and write the ICMP checksum in place.
///
/// RFC-REF: RFC 792
/// "The checksum is the 16-bit ones's complement of the one's complement
/// sum of the ICMP message starting with the ICMP Type."
fn compute_icmp_checksum(icmp_msg: &mut [u8]) {
    // Zero checksum field (bytes 2-3).
    icmp_msg[2] = 0x00;
    icmp_msg[3] = 0x00;
    let cksum = internet_checksum(icmp_msg);
    icmp_msg[2] = (cksum >> 8) as u8;
    icmp_msg[3] = (cksum & 0xFF) as u8;
}

/// Compute the Internet checksum (RFC 1071) over a byte slice.
fn internet_checksum(data: &[u8]) -> u16 {
    let mut sum: u32 = 0;
    for i in (0..data.len()).step_by(2) {
        let word = if i + 1 < data.len() {
            u16::from_be_bytes([data[i], data[i + 1]])
        } else {
            u16::from_be_bytes([data[i], 0])
        };
        sum += word as u32;
    }
    while (sum >> 16) != 0 {
        sum = (sum & 0xFFFF) + (sum >> 16);
    }
    !(sum as u16)
}

