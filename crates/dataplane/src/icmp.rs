    #[test]
    fn all_error_types_produce_correct_type_code() {
        let original = make_test_packet(
            [0xAA; 6],
            [0xBB; 6],
            [192, 168, 1, 100],
            [8, 8, 8, 8],
            64,
            17,
        );

        let cases = vec![
            (IcmpError::TtlExceeded, 11u8, 0u8),
            (IcmpError::NetUnreachable, 3, 0),
            (IcmpError::HostUnreachable, 3, 1),
        ];

        for (error, expected_type, expected_code) in cases {
            let reply = generate_icmp_error(&original, error, [10, 0, 0, 1], "eth0").unwrap();
            let icmp_start = ETH_HEADER_LEN + IPV4_HEADER_LEN;
            assert_eq!(
                reply.data[icmp_start], expected_type,
                "wrong ICMP type for {:?}",
                error
            );
            assert_eq!(
                reply.data[icmp_start + 1],
                expected_code,
                "wrong ICMP code for {:?}",
                error
            );
        }
    }
